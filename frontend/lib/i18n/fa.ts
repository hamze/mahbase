export type MessageKey = keyof typeof fa;

/** Tooltip text for a field name (``help.<field>``), when one is defined. */
export function help(field: string): string | undefined {
  const key = `help.${field}`;
  return key in fa ? fa[key as MessageKey] : undefined;
}

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  return Object.entries(vars).reduce<string>((text, [name, value]) => text.replace(`{${name}}`, String(value)), fa[key]);
}
